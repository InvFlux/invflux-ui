/**
 * Settings context. This package has no bundle of its own: the unified app imports its `App` as a
 * lazy section and passes this down from the app's own boot context, so nothing reads a global here.
 */
export interface AdminContext {
  /** REST root — either `…/index.php?rest_route=/` or `…/wp-json`. */
  apiRoot: string;
  nonce: string;
  capabilities: {
    manageSettings: boolean;
  };
  /**
   * Open with the "needs a decision" filter already applied — set by the host when the page was
   * reached from a link that promised exactly those settings (the first-run screen's count).
   *
   * The host owns this because the host owns the URL: this package has no router, and teaching it
   * to read query params would couple it to a scheme it does not otherwise know about.
   */
  startOnDecisions?: boolean;

  /**
   * The search term the host's URL carries, applied verbatim — including empty, which clears the
   * box. The URL is the single source of truth for the filter, so the two stay in step and a
   * filtered view is shareable, bookmarkable and survives a reload.
   *
   * Owned by the host for the same reason as `startOnDecisions`: this package has no router.
   */
  startSearch?: string;

  /**
   * A section to reveal on arrival, by its outline key — for a link generated by something other
   * than a person, such as an admin notice sending the merchant to the decision it just described.
   *
   * **A key, deliberately, and not a search term.** A term would have to be the section's
   * *translated* label, so a link minted in one locale would match nothing in another; a key is the
   * same in every language. Revealing also clears the "needs a decision" filter, which hides the
   * bespoke policy tables wholesale and would otherwise land the merchant on a page that still does
   * not show what they were sent to see.
   */
  revealSection?: string;

  /**
   * Called when the merchant changes the search term, so the host can mirror it into the URL.
   *
   * Absent — on the standalone page, which has no URL to mirror into — the box simply works without
   * being shareable.
   */
  onSearchChange?: (term: string) => void;
}
